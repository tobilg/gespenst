/** Lifecycle phase for a key input event. */
export type KeyAction = 'press' | 'repeat' | 'release';

/** Bit flags accepted by key and pointer input APIs. */
export const KeyModifiers = {
  /** Shift modifier bit. */
  shift: 1 << 0,
  /** Control modifier bit. */
  control: 1 << 1,
  /** Alt/Option modifier bit. */
  alt: 1 << 2,
  /** Meta/Command modifier bit. */
  meta: 1 << 3,
  /** Caps Lock modifier bit. */
  capsLock: 1 << 4,
  /** Num Lock modifier bit. */
  numLock: 1 << 5,
} as const;

/** A physical or composed keyboard input sent to Ghostty. */
export interface KeyInput {
  /** A KeyboardEvent.code value such as `KeyA`, `ArrowUp`, or `Enter`. */
  readonly code: string;
  /** Key lifecycle phase. Defaults to `press`. */
  readonly action?: KeyAction;
  /** Active {@link KeyModifiers} bit mask. */
  readonly modifiers?: number;
  /** Modifier bits already consumed by text generation. */
  readonly consumedModifiers?: number;
  /** Whether an input-method composition is active. */
  readonly composing?: boolean;
  /** Composed text associated with the key. */
  readonly text?: string;
  /** Unicode code point before keyboard-layout shifting. */
  readonly unshiftedCodepoint?: number;
}

