/** An RGB color with channels in the inclusive `0`-`255` range. */
export interface RgbColor {
  /** Red channel. */
  readonly r: number;
  /** Green channel. */
  readonly g: number;
  /** Blue channel. */
  readonly b: number;
}

/** An RGB color with an alpha channel between `0` and `1`. */
export interface RgbaColor extends RgbColor {
  /** Opacity from fully transparent (`0`) to fully opaque (`1`). */
  readonly a: number;
}

/** A portable CSS color string or structured RGB(A) value. */
export type TerminalColor = string | RgbColor | RgbaColor;

/** A normalized color used in render snapshots. */
export interface RenderColor extends RgbColor {
  /** Opacity. Omitted values are fully opaque. */
  readonly a?: number;
}

/** The color encoding authored by terminal output before theme palette resolution. */
export type CellColor =
  | {
      /** Use the terminal theme's default color. */
      readonly mode: 'default';
    }
  | {
      /** Resolve an indexed ANSI palette entry. */
      readonly mode: 'palette';
      /** Zero-based ANSI palette index. */
      readonly value: number;
    }
  | {
      /** Use an explicit RGB color. */
      readonly mode: 'rgb';
      /** Explicit color channels authored by terminal output. */
      readonly value: RgbColor;
    };

